"""Writes every TrackZero logo asset from generate.py's geometry: the SVG, the launcher vectors and the legacy PNGs.

    python3 design/logo/export.py      (needs Pillow)
"""
import importlib.util
import io
import math
import os
import sys

from PIL import Image, ImageDraw

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "..", "..", "android", "app", "src", "main", "res")

spec = importlib.util.spec_from_file_location("generate", os.path.join(HERE, "generate.py"))
g = importlib.util.module_from_spec(spec)
_err, sys.stderr = sys.stderr, io.StringIO()
spec.loader.exec_module(g)
sys.stderr = _err

MINT, AHEAD, BLACK = "#A9F7B9", "#5E8F68", "#000000"


def circle(x, y, r):
    return f"M{x - r:.2f},{y:.2f} a{r:.2f},{r:.2f} 0 1,0 {2 * r:.2f},0 a{r:.2f},{r:.2f} 0 1,0 {-2 * r:.2f},0 Z"


def write(path, text):
    with open(path, "w") as f:
        f.write(text)


# The SVG (the icon's visible 72 units, on its black ground).
write(os.path.join(HERE, "trackzero-logo.svg"),
      '<svg xmlns="http://www.w3.org/2000/svg" viewBox="18 18 72 72" width="512" height="512">\n'
      "  <title>TrackZero</title>\n"
      f'  <rect x="18" y="18" width="72" height="72" rx="16" fill="{BLACK}"/>\n'
      f"  {g.mark(dot_fill=AHEAD)}\n"
      "</svg>\n")

# Launcher foreground: the colour mark.
dots = " ".join(circle(x, y, g.DOT) for x, y in g.dots)
ring_bg, ring, ring_dot = circle(g.RX, g.RY, g.RING_BG), circle(g.RX, g.RY, g.RING_R), circle(g.RX, g.RY, g.RING_DOT)
VECTOR = ('<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
          '  android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">\n')
write(os.path.join(RES, "drawable", "ic_tz_launcher_foreground.xml"),
      '<?xml version="1.0" encoding="utf-8"?>\n'
      "<!--\n"
      "  TrackZero mark: a zero that is a loop ride. It starts and ends at the start ring (kilometre zero); the part ridden\n"
      "  is a solid mint line, the road ahead mint dots, dimmed as a route not yet ridden.\n"
      "  Generated by design/logo/export.py: edit generate.py there, not this file.\n"
      "-->\n" + VECTOR +
      f'  <path android:pathData="{g.SP}" android:strokeColor="@color/tz_mint" android:strokeWidth="{g.LINE:.2f}"\n'
      '    android:strokeLineCap="round" android:strokeLineJoin="round"/>\n'
      f'  <path android:pathData="{dots}" android:fillColor="@color/tz_logo_ahead"/>\n'
      f'  <path android:pathData="{ring_bg}" android:fillColor="@color/tz_bg"/>\n'
      f'  <path android:pathData="{ring}" android:strokeColor="@color/tz_mint" android:strokeWidth="{g.RING_W:.2f}"/>\n'
      f'  <path android:pathData="{ring_dot}" android:fillColor="@color/tz_mint"/>\n'
      "</vector>\n")

# Themed icon (Android 13+ draws it as a silhouette): no disc behind the ring, so the line stops short of it.
center = (g.RX, g.RY)
clear = g.RING_R + g.RING_W / 2 + 1.0 * g.K + g.LINE / 2
s = 0.0
while math.dist(g.at(s), center) < clear:
    s += 0.02
write(os.path.join(RES, "drawable", "ic_tz_launcher_monochrome.xml"),
      '<?xml version="1.0" encoding="utf-8"?>\n'
      "<!-- The TrackZero mark in one colour for themed icons. Generated by design/logo/export.py. -->\n" + VECTOR +
      f'  <path android:pathData="{g.SP}" android:strokeColor="#FFFFFFFF" android:strokeWidth="{g.LINE:.2f}"\n'
      f'    android:strokeLineCap="round" android:strokeLineJoin="round" android:trimPathStart="{s / g.solid_end:.4f}"/>\n'
      f'  <path android:pathData="{dots}" android:fillColor="#FFFFFFFF"/>\n'
      f'  <path android:pathData="{ring}" android:strokeColor="#FFFFFFFF" android:strokeWidth="{g.RING_W:.2f}"/>\n'
      f'  <path android:pathData="{ring_dot}" android:fillColor="#FFFFFFFF"/>\n'
      "</vector>\n")


# Legacy launchers (Android 7 and older) show the PNG unmasked: the visible 72 units on a rounded black square.
def rgba(hex_color):
    return tuple(int(hex_color[i:i + 2], 16) for i in (1, 3, 5)) + (255,)


def render(px):
    scale = 8
    w = px * scale
    im = Image.new("RGBA", (w, w), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    d.rounded_rectangle([0, 0, w - 1, w - 1], radius=int(w * 0.22), fill=rgba(BLACK))
    k = w / 72.0

    def at(x, y):
        return (x - 18) * k, (y - 18) * k

    def dab(x, y, r, color):
        d.ellipse([x - r, y - r, x + r, y + r], fill=color)

    for i in range(1201):  # round dabs along the ridden line: round caps and joins
        dab(*at(*g.at(g.solid_end * i / 1200)), g.LINE / 2 * k, rgba(MINT))
    for x, y in g.dots:
        dab(*at(x, y), g.DOT * k, rgba(AHEAD))
    cx, cy = at(g.RX, g.RY)
    for r, color in ((g.RING_BG, BLACK), (g.RING_R + g.RING_W / 2, MINT), (g.RING_R - g.RING_W / 2, BLACK),
                     (g.RING_DOT, MINT)):
        dab(cx, cy, r * k, rgba(color))
    return im.resize((px, px), Image.LANCZOS)


for dpi, px in {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}.items():
    render(px).save(os.path.join(RES, f"mipmap-{dpi}", "ic_launcher.png"))
render(512).save(os.path.join(HERE, "trackzero-logo-512.png"))
print("TrackZero logo exported")
